const DICT: Record<Lang, typeof AR> = { ar: AR, en: EN }

type Ctx = { lang: Lang; t: (k: keyof typeof AR) => string; toggle: () => void }
const I18nCtx = createContext<Ctx>({ lang: 'ar', t: (k) => AR[k], toggle: () => {} })

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>('ar')
  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.body.style.fontFamily = lang === 'ar' ? "'Tajawal','Inter',system-ui" : "'Inter','Tajawal',system-ui"
  }, [lang])
  const t = (k: keyof typeof AR) => DICT[lang][k]
  return <I18nCtx.Provider value={{ lang, t, toggle: () => setLang((l) => (l === 'ar' ? 'en' : 'ar')) }}>{children}</I18nCtx.Provider>
}

export const useI18n = () => useContext(I18nCtx)